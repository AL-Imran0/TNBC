def tta_predict(model, imgs):
    preds = []
    # original
    preds.append(model.predict(imgs, verbose=0))
    # hflip
    hf = np.flip(imgs, axis=2)
    p = np.flip(model.predict(hf, verbose=0), axis=2)
    preds.append(p)
    # vflip
    vf = np.flip(imgs, axis=1)
    p = np.flip(model.predict(vf, verbose=0), axis=1)
    preds.append(p)
    # rot90
    r = np.rot90(imgs, k=1, axes=(1,2))
    p = np.rot90(model.predict(r, verbose=0), k=3, axes=(1,2))
    preds.append(p)
    # average
    avg = np.mean(preds, axis=0)
    return avg

