def batch_generator(X_arr, Y_arr, batch_size=8, aug=None):
    N = len(X_arr)
    idxs = np.arange(N)
    while True:
        np.random.shuffle(idxs)
        for i in range(0, N, batch_size):
            batch_idx = idxs[i:i+batch_size]
            imgs = []
            masks = []
            for j in batch_idx:
                img = (X_arr[j]*255).astype('uint8')
                mask = (Y_arr[j][:,:,0]*255).astype('uint8')
                if aug:
                    a = aug(image=img, mask=mask)
                    img_a, mask_a = a['image'], a['mask']
                else:
                    img_a, mask_a = img, mask
                imgs.append(img_a.astype('float32')/255.0)
                masks.append(np.expand_dims((mask_a>127).astype('float32'), -1))
            yield np.array(imgs), np.array(masks)

