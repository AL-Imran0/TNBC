# Compute metrics (image-wise dice already, plus pixel-level precision/recall/f1/auc)
from sklearn.metrics import precision_recall_fscore_support, roc_auc_score, accuracy_score

def compute_metrics(y_true, y_pred_bin, y_pred_prob):
    # accuracy per pixel
    acc = (y_true == y_pred_bin).mean()
    # dice per image (binary)
    dice_vals = []
    for i in range(len(y_true)):
        y_t = y_true[i].flatten()
        y_pb = y_pred_bin[i].flatten()
        inter = (y_pb * y_t).sum()
        dice = (2*inter) / (y_pb.sum() + y_t.sum() + 1e-6)
        dice_vals.append(dice)
    mean_dice = np.mean(dice_vals)
    # flatten to compute precision/recall/f1 and AUC across all pixels
    y_true_flat = y_true.reshape(-1)
    y_pred_bin_flat = y_pred_bin.reshape(-1)
    y_pred_prob_flat = y_pred_prob.reshape(-1)
    precision, recall, f1, _ = precision_recall_fscore_support(y_true_flat, y_pred_bin_flat, average='binary', zero_division=0)
    # roc auc: may fail if only one class present -> handle
    try:
        auc = roc_auc_score(y_true_flat, y_pred_prob_flat)
    except Exception as e:
        auc = float('nan')
    return acc, mean_dice, precision, recall, f1, auc

