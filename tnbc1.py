def extract_patches_from_pair(img_path, mask_path, patches_per_image=PATCHES_PER_IMAGE, patch_size=IMG_SIZE):
    img = cv2.imread(img_path)
    mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)
    if img is None or mask is None:
        return [], []
    h,w = mask.shape
    patches_img = []
    patches_mask = []
    tries = 0
    max_tries = patches_per_image * 20
    while len(patches_img) < patches_per_image and tries < max_tries:
        tries += 1
        x = random.randint(0, max(0, w - patch_size))
        y = random.randint(0, max(0, h - patch_size))
        mpatch = mask[y:y+patch_size, x:x+patch_size]
        ipatch = img[y:y+patch_size, x:x+patch_size]
        if ipatch.shape[0] != patch_size or ipatch.shape[1] != patch_size:
            continue
        frac = (mpatch > 127).sum() / (patch_size * patch_size)
        prob = 0.9 if frac > 0.005 else 0.2
        if random.random() < prob:
            patches_img.append(ipatch)
            _, binmask = cv2.threshold(mpatch, 127, 255, cv2.THRESH_BINARY)
            patches_mask.append(binmask)
    while len(patches_img) < patches_per_image:
        x = random.randint(0, max(0, w - patch_size))
        y = random.randint(0, max(0, h - patch_size))
        ipatch = img[y:y+patch_size, x:x+patch_size]
        mpatch = mask[y:y+patch_size, x:x+patch_size]
        if ipatch.shape[0] != patch_size or ipatch.shape[1] != patch_size:
            continue
        patches_img.append(ipatch)
        _, binmask = cv2.threshold(mpatch, 127, 255, cv2.THRESH_BINARY)
        patches_mask.append(binmask)
    return patches_img, patches_mask

