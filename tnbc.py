def kmer_counts(series, k=3, top_k=200):
    # produce top_k common k-mers across whole column and return DataFrame
    from collections import Counter
    all_kmers = Counter()
    for s in series.dropna().astype(str):
        s = ''.join(filter(str.isalpha, s)).upper()
        kmers = [s[i:i+k] for i in range(len(s)-k+1)] if len(s) >= k else []
        all_kmers.update(kmers)
    most = [kmer for kmer,_ in all_kmers.most_common(top_k)]
    # build matrix
    mat = np.zeros((len(series), len(most)), dtype=np.float32)
    idx = 0
    for s in series.astype(str).fillna(""):
        s2 = ''.join(filter(str.isalpha, s)).upper()
        kmers = [s2[i:i+k] for i in range(len(s2)-k+1)] if len(s2)>=k else []
        cnt = Counter(kmers)
        for j,kmer in enumerate(most):
            mat[idx,j] = cnt.get(kmer, 0)
        idx += 1
    return pd.DataFrame(mat, index=series.index, columns=[f"{series.name}_k{k}_{i}" for i in range(len(most))])

