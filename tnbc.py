# 7. Autoencoder + Classifier
# =============================
def train_autoencoder_classifier(X_train, X_test, y_train, y_test, epochs=20):
    encoding_dim = 128
    input_dim = X_train.shape[1]

    # Autoencoder
    input_layer = layers.Input(shape=(input_dim,))
    encoded = layers.Dense(encoding_dim, activation="relu")(input_layer)
    decoded = layers.Dense(input_dim, activation="sigmoid")(encoded)
    autoencoder = keras.Model(input_layer, decoded)
    autoencoder.compile(optimizer="adam", loss="mse")
    autoencoder.fit(X_train, X_train, epochs=epochs, batch_size=32, validation_split=0.2, verbose=0)

    # Encoder
    encoder = keras.Model(input_layer, encoded)
    X_train_enc = encoder.predict(X_train)
    X_test_enc = encoder.predict(X_test)

    # Classifier
    clf = keras.Sequential([
        layers.Input(shape=(encoding_dim,)),
        layers.Dense(64, activation="relu"),
        layers.Dense(1, activation="sigmoid")
    ])
    clf.compile(optimizer="adam", loss="binary_crossentropy", metrics=["accuracy"])
    clf.fit(X_train_enc, y_train, epochs=epochs, batch_size=32, validation_data=(X_test_enc, y_test), verbose=0)

    # Train eval
    y_pred_train = (clf.predict(X_train_enc) > 0.5).astype("int32")
    y_prob_train = clf.predict(X_train_enc).ravel()
    train_metrics = evaluate_model(y_train, y_pred_train, y_prob_train)

    # Test eval
    y_pred_test = (clf.predict(X_test_enc) > 0.5).astype("int32")
    y_prob_test = clf.predict(X_test_enc).ravel()
    test_metrics = evaluate_model(y_test, y_pred_test, y_prob_test)

    print("\nAutoencoder+Classifier Results")
    print("Train:", train_metrics)
    print("Test :", test_metrics)
    return {"Autoencoder+Classifier": (train_metrics, test_metrics)}

