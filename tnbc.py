def extract_head(file_path, n_example_rows=1):
    header = None
    example_rows = []

    with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            stripped = line.strip()
            if not stripped:
                continue

            # detect tab-separated line with multiple fields
            parts = stripped.split("\t")
            if len(parts) > 1:
                header = parts
                break

        # read the next few lines as examples
        for _ in range(n_example_rows):
            try:
                row = next(f).strip()
                if row:
                    example_rows.append(row)
            except StopIteration:
                break

    return header, example_rows


