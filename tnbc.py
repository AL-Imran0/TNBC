def normalize_label(series):
    s = series.astype(str).str.strip().str.lower()
    # common positive tokens:
    pos_tokens = ['tnbc', 'triple negative', 'triple_negative', 'positive', 'pos', '1', 'yes', 'y', 'true', 't']
    neg_tokens = ['non-tnbc', 'non tnbc', 'non','negative','neg','0','no','n','false','f','her2','er_pos','er+']
    # map
    out = []
    for v in s:
        if pd.isna(v) or v=='':
            out.append(np.nan)
            continue
        found = False
        for t in pos_tokens:
            if t in v:
                out.append(1); found=True; break
        if found: continue
        for t in neg_tokens:
            if t in v:
                out.append(0); found=True; break
        if found: continue
        # numeric fallback
        try:
            vn = float(v)
            out.append(1 if vn==1 else 0 if vn==0 else np.nan)
        except:
            # as fallback, map first observed value as 1 and second as 0
            out.append(v)  # keep as string to be label-encoded later
    return pd.Series(out, index=series.index)

