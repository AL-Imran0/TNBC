# 3. Preprocessing Function
# =============================
def preprocess_data(df, target="LABEL", kbest=200, test_size=0.2):
    if target not in df.columns:
        raise ValueError(f"Target column '{target}' not found in dataframe!")

    df = df.copy()
    y = df[target]

    # Separate features
    X = df.drop(columns=[target])

    # Identify numeric and categorical columns
    numeric_cols = X.select_dtypes(include=[np.number]).columns.tolist()
    categorical_cols = X.select_dtypes(exclude=[np.number]).columns.tolist()

    if len(numeric_cols) + len(categorical_cols) == 0:
        raise ValueError("No features available for preprocessing!")

    # Preprocessing: impute numeric, one-hot encode categorical
    numeric_transformer = SimpleImputer(strategy="median")
    categorical_transformer = OneHotEncoder(handle_unknown="ignore", sparse_output=False)

    preprocessor = ColumnTransformer(
        transformers=[
            ("num", numeric_transformer, numeric_cols),
            ("cat", categorical_transformer, categorical_cols)
        ]
    )

    X_processed = preprocessor.fit_transform(X)
    print(f"Features after preprocessing: {X_processed.shape}")

    # Scale all features
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X_processed)

    # Feature selection
    kbest = min(kbest, X_scaled.shape[1])
    if kbest > 0:
        selector = SelectKBest(f_classif, k=kbest)
        X_selected = selector.fit_transform(X_scaled, y)
    else:
        X_selected = X_scaled

    # Train/test split
    X_train, X_test, y_train, y_test = train_test_split(
        X_selected, y, test_size=test_size, random_state=42, stratify=y
    )
    print(f"Preprocessing done: X_train shape {X_train.shape}, X_test shape {X_test.shape}")
    return X_train, X_test, y_train, y_test

# =============================
# 4. Evaluation Function (Acc, Prec, Recall, F1, AUC)
# =============================
def evaluate_model(y_true, y_pred, y_prob):
    acc = accuracy_score(y_true, y_pred)
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_true, y_pred, average="binary", zero_division=0
    )
    try:
        auc = roc_auc_score(y_true, y_prob)
    except:
        auc = float("nan")
    return acc, precision, recall, f1, auc

# =============================
# 5. Classical ML Models
# =============================
def train_ml_models(X_train, X_test, y_train, y_test):
    models = {
        "RandomForest": RandomForestClassifier(n_estimators=200, random_state=42),
        "GradientBoosting": GradientBoostingClassifier(random_state=42),
        "LogReg": LogisticRegression(max_iter=200, random_state=42),
        "SVM": SVC(probability=True, random_state=42)
    }
    results = {}
    for name, model in models.items():
        model.fit(X_train, y_train)

        # --- Train eval ---
        y_pred_train = model.predict(X_train)
        y_prob_train = model.predict_proba(X_train)[:,1]
        train_metrics = evaluate_model(y_train, y_pred_train, y_prob_train)

        # --- Test eval ---
        y_pred_test = model.predict(X_test)
        y_prob_test = model.predict_proba(X_test)[:,1]
        test_metrics = evaluate_model(y_test, y_pred_test, y_prob_test)

        results[name] = (train_metrics, test_metrics)

        print(f"\n{name} Results")
        print("Train:", train_metrics)
        print("Test :", test_metrics)
        print("Confusion Matrix:\n", confusion_matrix(y_test, y_pred_test))
        print("Classification Report:\n", classification_report(y_test, y_pred_test))
    return results

# =============================
# 6. ANN Model
# =============================
def train_ann(X_train, X_test, y_train, y_test, epochs=20):
    model = keras.Sequential([
        layers.Input(shape=(X_train.shape[1],)),
        layers.Dense(256, activation="relu"),
        layers.Dropout(0.3),
        layers.Dense(128, activation="relu"),
        layers.Dropout(0.2),
        layers.Dense(64, activation="relu"),
        layers.Dense(1, activation="sigmoid")
    ])
    model.compile(optimizer="adam", loss="binary_crossentropy", metrics=["accuracy"])
    model.fit(X_train, y_train, epochs=epochs, batch_size=32,
              validation_data=(X_test, y_test), verbose=0)

    # Train eval
    y_pred_train = (model.predict(X_train) > 0.5).astype("int32")
    y_prob_train = model.predict(X_train).ravel()
    train_metrics = evaluate_model(y_train, y_pred_train, y_prob_train)

    # Test eval
    y_pred_test = (model.predict(X_test) > 0.5).astype("int32")
    y_prob_test = model.predict(X_test).ravel()
    test_metrics = evaluate_model(y_test, y_pred_test, y_prob_test)

    print("\nANN Results")
    print("Train:", train_metrics)
    print("Test :", test_metrics)
    return {"ANN": (train_metrics, test_metrics)}

